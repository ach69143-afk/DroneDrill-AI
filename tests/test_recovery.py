"""Unit tests for DroneDrill AI Ground-Truth Skill Recovery.

Requirement:
After 40 sessions a SimLearner's posterior means correlate with its true condition skills (r > 0.7).
Print r; this is our validation evidence.
"""

import numpy as np
from scipy.stats import pearsonr

from app.db import init_db
from app.factors import PRACTICE_CELLS
from app.generator import generate_for_cell, _coerce_rng
from app.skill_model import update_from_result, get_posterior, SKILLS
from app.sim_learner import SimLearner


def test_sim_learner_skill_recovery(tmp_path):
    """Requirement: after 40 sessions a SimLearner's posterior means correlate with its true condition skills (r > 0.7). Print r; this is our validation evidence."""
    db_file = str(tmp_path / "recovery_test.db")
    init_db(db_file)
    trainee_id = "trainee_recovery_agent"

    # Define ground-truth skills across weather and time_of_day condition levels
    condition_skills = {
        ("weather", "clear"): 0.92,
        ("weather", "haze"): 0.75,
        ("weather", "dust"): 0.55,
        ("weather", "rain"): 0.35,
        ("weather", "fog"): 0.15,
        ("time_of_day", "day"): 0.88,
        ("time_of_day", "dusk"): 0.55,
        ("time_of_day", "night"): 0.20,
    }

    learner = SimLearner(
        base_skill=0.60,
        condition_skills=condition_skills,
        rote_bonus=0.0,
        rng=42,
    )

    practice_list = sorted(list(PRACTICE_CELLS))
    rng = _coerce_rng(42)

    from app.factors import CONDITION_FACTOR_NAMES
    levels_to_test = list(condition_skills.keys())

    # Run 40 training sessions cycling through the tested condition levels (5 sessions per level)
    for i in range(40):
        target_factor, target_level = levels_to_test[i % len(levels_to_test)]
        f_idx = CONDITION_FACTOR_NAMES.index(target_factor)

        # Baseline control: hold non-target factor neutral to accurately recover condition response
        if target_factor == "weather":
            matching = [c for c in practice_list if c[f_idx] == target_level and c[0] == "day"]
        else:
            matching = [c for c in practice_list if c[f_idx] == target_level and c[1] == "clear"]

        if not matching:
            matching = [c for c in practice_list if c[f_idx] == target_level]

        cell = matching[i % len(matching)]
        scenario = generate_for_cell(cell, rng=rng)

        scores = learner.evaluate_scenario(scenario)
        update_from_result(trainee_id, scores["skill_scores"], db_path=db_file)

    # Collect ground-truth and posterior recovered means
    true_skills = []
    recovered_means = []

    for (factor, level), true_val in condition_skills.items():
        # Average posterior across the 5 core skills
        means = [
            get_posterior(trainee_id, skill, factor, level, db_path=db_file)["mean"]
            for skill in SKILLS
        ]
        avg_mean = float(np.mean(means))
        true_skills.append(true_val)
        recovered_means.append(avg_mean)

    r_val, p_val = pearsonr(true_skills, recovered_means)

    # Write r and session count to data/validation_report.json
    try:
        from pathlib import Path
        import json
        repo_root = Path(__file__).resolve().parent.parent
        report_file = repo_root / "data" / "validation_report.json"
        report_file.parent.mkdir(parents=True, exist_ok=True)
        report_payload = {
            "metric": "Pearson correlation (true condition skill vs. Bayesian posterior mean)",
            "r": round(float(r_val), 4),
            "p_value": float(p_val),
            "sessions": 40,
            "trainee_id": trainee_id,
            "status": "VALIDATED" if r_val > 0.7 else "FAIL",
            "threshold": 0.70,
            "note": "Generated by test_recovery.py on synthetic SimLearner across 40 training sessions.",
        }
        with open(report_file, "w", encoding="utf-8") as f:
            json.dump(report_payload, f, indent=2)
    except Exception as save_err:
        print(f"Warning: Failed to write validation report: {save_err}")

    # Print r as specified in the requirements
    print(f"\n==========================================")
    print(f"Validation evidence: Skill Recovery Correlation r = {r_val:.4f} (p = {p_val:.2e})")
    print(f"==========================================\n")

    assert r_val > 0.7, f"Expected Pearson correlation r > 0.7, got {r_val:.4f}"

